#!/usr/bin/env bash
set -euo pipefail

# Qwen3-1.7B paper configuration. The verifier determines update direction;
# the teacher only scales positive credit within selected correct spans.

export NUM_PROCESSES="${NUM_PROCESSES:-4}"
export MAIN_PROCESS_PORT="${MAIN_PROCESS_PORT:-13031}"
export NUM_STUDENT_SAMPLES="${NUM_STUDENT_SAMPLES:-16}"
export MAX_COMPLETION_LENGTH="${MAX_COMPLETION_LENGTH:-768}"
export VLLM_GPU_MEMORY_UTILIZATION="${VLLM_GPU_MEMORY_UTILIZATION:-0.14}"
export TEACHER_SCORE_MICRO_BATCH="${TEACHER_SCORE_MICRO_BATCH:-1}"

export LEARNING_RATE="${LEARNING_RATE:-3e-6}"
export WARMUP_RATIO="${WARMUP_RATIO:-0.08}"
export LR_SCHEDULER_TYPE="${LR_SCHEDULER_TYPE:-cosine}"
export MAX_GRAD_NORM="${MAX_GRAD_NORM:-0.25}"
export NUM_TRAIN_EPOCHS="${NUM_TRAIN_EPOCHS:-3}"

export TEMPERATURE="${TEMPERATURE:-0.95}"
export TOP_P="${TOP_P:-0.85}"
export TOP_K="${TOP_K:-30}"
export REPETITION_PENALTY="${REPETITION_PENALTY:-1.05}"

export GRPO_COEF="${GRPO_COEF:-1.5}"
export GRPO_LOSS_CLIP="${GRPO_LOSS_CLIP:-0.5}"
export GRPO_LOGP_CLIP="${GRPO_LOGP_CLIP:-10.0}"
export ADVANTAGE_CLIP="${ADVANTAGE_CLIP:-3.0}"

# Keep positive local credit active without allowing broad imitation to dominate.
export SPAN_DISTILL_COEF="${SPAN_DISTILL_COEF:-0.012}"
export SPAN_COEF_FLOOR="${SPAN_COEF_FLOOR:-0.0015}"
export SPAN_DECAY_START_RATIO="${SPAN_DECAY_START_RATIO:-0.55}"
export SPAN_DECAY_END_RATIO="${SPAN_DECAY_END_RATIO:-0.92}"
export SPAN_RANK_FLOOR="${SPAN_RANK_FLOOR:-0.25}"
export SPAN_GAIN_WEIGHT_FLOOR="${SPAN_GAIN_WEIGHT_FLOOR:-1.0}"
export SPAN_GAIN_WEIGHT_SCALE="${SPAN_GAIN_WEIGHT_SCALE:-1.0}"
export SPAN_TRAJ_NORMALIZE="${SPAN_TRAJ_NORMALIZE:-False}"
export SPAN_MAX_TRAJ_WEIGHT="${SPAN_MAX_TRAJ_WEIGHT:-1.0}"

# Answer and diff are the reliable, explainable span families. Support/reason
# become a tiny late regularizer instead of a wide SFT-like objective.
export ANSWER_SPAN_WEIGHT="${ANSWER_SPAN_WEIGHT:-0.55}"
export DIFF_SPAN_WEIGHT="${DIFF_SPAN_WEIGHT:-1.20}"
export CALCULATION_SPAN_WEIGHT="${CALCULATION_SPAN_WEIGHT:-0.0}"
export SUPPORT_SPAN_WEIGHT="${SUPPORT_SPAN_WEIGHT:-0.012}"
export REASON_SPAN_WEIGHT="${REASON_SPAN_WEIGHT:-0.0}"
export ANSWER_SPAN_TOKENS="${ANSWER_SPAN_TOKENS:-64}"
export DIFF_SPAN_TOKENS="${DIFF_SPAN_TOKENS:-96}"
export DIFF_SPAN_TOP_K="${DIFF_SPAN_TOP_K:-2}"
export CALCULATION_SPAN_TOKENS="${CALCULATION_SPAN_TOKENS:-64}"
export SUPPORT_SPAN_TOKENS="${SUPPORT_SPAN_TOKENS:-48}"
export REASON_SPAN_TOKENS="${REASON_SPAN_TOKENS:-48}"
export SUPPORT_START_RATIO="${SUPPORT_START_RATIO:-0.72}"
export REASON_START_RATIO="${REASON_START_RATIO:-0.90}"
export POSITIVE_TEACHER_SPAN_ONLY="${POSITIVE_TEACHER_SPAN_ONLY:-True}"
export POSITIVE_REASON_SPAN_ONLY="${POSITIVE_REASON_SPAN_ONLY:-True}"

# Error suppression should only be a small guardrail. Too much suppress hurts
# pass by making samples converge toward one cautious mode.
export ERROR_SUPPRESS_COEF="${ERROR_SUPPRESS_COEF:-0.0012}"
export ERROR_SUPPRESS_MAX_RATIO="${ERROR_SUPPRESS_MAX_RATIO:-0.03}"
export ERROR_SUPPRESS_MAX_SPAN_RATIO="${ERROR_SUPPRESS_MAX_SPAN_RATIO:-0.0}"
export ERROR_SUPPRESS_START_RATIO="${ERROR_SUPPRESS_START_RATIO:-0.55}"

# Preserve broad coverage while prioritizing mixed groups.
export CURRICULUM_ALPHA_START="${CURRICULUM_ALPHA_START:-1.20}"
export CURRICULUM_ALPHA_END="${CURRICULUM_ALPHA_END:-0.40}"
export CURRICULUM_STAGE1_RATIO="${CURRICULUM_STAGE1_RATIO:-0.20}"
export CURRICULUM_STAGE2_RATIO="${CURRICULUM_STAGE2_RATIO:-0.62}"
export CURRICULUM_STAGE3_RATIO="${CURRICULUM_STAGE3_RATIO:-0.84}"
export CURRICULUM_MEMORY_MOMENTUM="${CURRICULUM_MEMORY_MOMENTUM:-0.50}"
export CURRICULUM_MEMORY_BLEND="${CURRICULUM_MEMORY_BLEND:-0.30}"
export CURRICULUM_WEIGHT_FLOOR="${CURRICULUM_WEIGHT_FLOOR:-0.15}"
export CURRICULUM_REVIEW_MIX_MAX="${CURRICULUM_REVIEW_MIX_MAX:-0.08}"
export CURRICULUM_SAMPLER_ENABLED="${CURRICULUM_SAMPLER_ENABLED:-False}"
export ADAPTIVE_CURRICULUM_ENABLED="${ADAPTIVE_CURRICULUM_ENABLED:-False}"
export MIXED_BALANCE_BONUS="${MIXED_BALANCE_BONUS:-0.0}"

# Length/stop guard: do not flip the reward sign; only reduce the magnitude of
# already-correct answers that keep writing after a final answer, and add a tiny
# EOS likelihood term at the final-answer boundary.
export WRONG_LENGTH_BOOST="${WRONG_LENGTH_BOOST:-0.25}"
export TRUNCATED_NEGATIVE_WEIGHT="${TRUNCATED_NEGATIVE_WEIGHT:-0.0}"
export NEAR_FULL_NEGATIVE_RATIO="${NEAR_FULL_NEGATIVE_RATIO:-1.0}"
export CORRECT_NEAR_FULL_POSITIVE_WEIGHT="${CORRECT_NEAR_FULL_POSITIVE_WEIGHT:-0.55}"
export POST_ANSWER_GRPO_WEIGHT="${POST_ANSWER_GRPO_WEIGHT:-0.15}"
export ANSWER_STOP_LOSS_COEF="${ANSWER_STOP_LOSS_COEF:-0.0008}"
export ANSWER_STOP_GRACE_TOKENS="${ANSWER_STOP_GRACE_TOKENS:-2}"
export NO_ANSWER_FULL_LENGTH_WEIGHT="${NO_ANSWER_FULL_LENGTH_WEIGHT:-1.0}"

# Bound teacher magnitude to preserve exploration.
export USE_PRIVILEGED_GAIN="${USE_PRIVILEGED_GAIN:-True}"
export TEACHER_STEP_WINDOW="${TEACHER_STEP_WINDOW:-21}"
export TEACHER_STUDENT_GAP_COEF="${TEACHER_STUDENT_GAP_COEF:-0.0}"
export TEACHER_PRIVILEGED_CONFIDENCE_COEF="${TEACHER_PRIVILEGED_CONFIDENCE_COEF:-0.0}"
export TEACHER_GROUP_SUPPORT_FLOOR="${TEACHER_GROUP_SUPPORT_FLOOR:-0.18}"
export TEACHER_SUPPORT_MAX="${TEACHER_SUPPORT_MAX:-1.35}"
export TEACHER_GRPO_MAGNITUDE_COEF="${TEACHER_GRPO_MAGNITUDE_COEF:-1.0}"
export TEACHER_CORRECT_LENGTH_DAMPEN="${TEACHER_CORRECT_LENGTH_DAMPEN:-0.15}"
export TEACHER_STEP_RANK_FLOOR="${TEACHER_STEP_RANK_FLOOR:-0.70}"
export TEACHER_TOKEN_WEIGHT_CLIP="${TEACHER_TOKEN_WEIGHT_CLIP:-1.25}"

# Disable optional confidence and trace-context extensions in the paper setup.
export VERIFIER_CONFIDENCE_ENABLED="${VERIFIER_CONFIDENCE_ENABLED:-False}"
export TRACE_CONTEXT_TOPK="${TRACE_CONTEXT_TOPK:-0}"
export TRACE_CONTEXT_MAX_TOKENS="${TRACE_CONTEXT_MAX_TOKENS:-64}"

export ALL_WRONG_PENALTY="${ALL_WRONG_PENALTY:-0.0}"
export ALL_WRONG_DATA_WEIGHT="${ALL_WRONG_DATA_WEIGHT:-0.0}"
export ALL_CORRECT_BONUS="${ALL_CORRECT_BONUS:-0.0}"
export ALL_CORRECT_DATA_WEIGHT="${ALL_CORRECT_DATA_WEIGHT:-0.0}"
export FINAL_SPAN_WEIGHT="${FINAL_SPAN_WEIGHT:--1.0}"
export CONTRAST_SPAN_WEIGHT="${CONTRAST_SPAN_WEIGHT:--1.0}"
export CONTEXT_SPAN_WEIGHT="${CONTEXT_SPAN_WEIGHT:--1.0}"
export SPAN_EVIDENCE_FLOOR="${SPAN_EVIDENCE_FLOOR:--1.0}"

export SAVE_STEPS="${SAVE_STEPS:-25}"
export SAVE_TOTAL_LIMIT="${SAVE_TOTAL_LIMIT:-16}"
export RUN_CONFIG="${RUN_CONFIG:-cpd_qwen3_1p7b}"

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
exec bash "${SCRIPT_DIR}/train_cpd.sh"

